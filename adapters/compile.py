def clean_adapters(base_dir: Path):
    """Removes all generated adapter directories and files."""
    targets = [
        base_dir / ".agents",
        base_dir / ".claude",
        base_dir / ".cursor",
        base_dir / ".github" / "copilot-instructions.md"
    ]
    removed = 0
    for target in targets:
        if target.is_dir():
            shutil.rmtree(target)
            print(f"  [REMOVED DIR] {target}")
            removed += 1
        elif target.is_file():
            target.unlink()
            print(f"  [REMOVED FILE] {target}")
            removed += 1
    # Remove .github if empty
    gh_dir = base_dir / ".github"
    if gh_dir.exists() and not any(gh_dir.iterdir()):
        gh_dir.rmdir()
        print(f"  [REMOVED EMPTY DIR] {gh_dir}")
    print(f"Cleanup complete. Removed {removed} adapter targets.")

def verify_adapters(base_dir: Path) -> bool:
    """Verifies that generated adapter shims point to valid canonical targets."""
    checks = [
        (base_dir / ".agents" / "rules" / "orchestrator.md", "Antigravity rule"),
        (base_dir / ".claude" / "commands" / "orchestrator.md", "Claude Code command"),
        (base_dir / ".cursor" / "rules" / "orchestrator.mdc", "Cursor rule"),
        (base_dir / ".github" / "copilot-instructions.md", "Copilot instructions")
    ]
    all_ok = True
    for path, name in checks:
        if not path.exists():
            print(f"  [MISSING] {name} at {path}")
            all_ok = False
        else:
            text = path.read_text(encoding="utf-8")
            if "canonical/agents/orchestrator.md" not in text:
                print(f"  [FAIL] {name} does not reference canonical orchestrator")
                all_ok = False
            else:
                print(f"  [PASS] {name} correctly references canonical orchestrator")
    return all_ok

def main():
    parser = argparse.ArgumentParser(description="Generate optional IDE convenience shims for Universal Agent Army.")
    parser.add_argument(
        "--target",
        choices=["all", "antigravity", "claude", "cursor", "copilot"],
        default="all",
        help="Target IDE platform (default: all)"
    )
    parser.add_argument("--clean", action="store_true", help="Remove all generated adapter files")
    parser.add_argument("--verify", action="store_true", help="Verify existing adapter shims")

    args = parser.parse_args()

    if args.clean:
        print("Cleaning optional IDE adapter files...")
        clean_adapters(BASE_DIR)
        return

    if args.verify:
        print("Verifying optional IDE adapter shims...")
        ok = verify_adapters(BASE_DIR)
        sys.exit(0 if ok else 1)

    print(f"Compiling optional IDE pointer shims for target: '{args.target}'...")
    created = []
    if args.target in ("all", "antigravity"):
        created.extend(generate_antigravity(BASE_DIR))
    if args.target in ("all", "claude"):
        created.extend(generate_claude(BASE_DIR))
    if args.target in ("all", "cursor"):
        created.extend(generate_cursor(BASE_DIR))
    if args.target in ("all", "copilot"):
        created.extend(generate_copilot(BASE_DIR))

    print(f"Successfully generated {len(created)} thin adapter pointer files.")

if __name__ == "__main__":
    main()
