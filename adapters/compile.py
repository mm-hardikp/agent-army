#!/usr/bin/env python3
"""compile.py - Zero-dependency generator for optional IDE convenience shims."""

import os
import sys
import shutil
import argparse
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
CANONICAL_DIR = BASE_DIR / "canonical"
AGENTS_DIR = CANONICAL_DIR / "agents"
SKILLS_DIR = CANONICAL_DIR / "skills"
WORKFLOWS_DIR = CANONICAL_DIR / "workflows"

def generate_antigravity(base_dir: Path) -> list:
    """Generates Google Antigravity thin rule and skill stubs."""
    created = []
    rules_dir = base_dir / ".agents" / "rules"
    skills_dir = base_dir / ".agents" / "skills"
    rules_dir.mkdir(parents=True, exist_ok=True)
    skills_dir.mkdir(parents=True, exist_ok=True)

    # 1. Orchestrator rule
    orch_rule = rules_dir / "orchestrator.md"
    content = """# Antigravity Rule: Universal Orchestrator
<!-- Generated by adapters/compile.py. Do not edit directly. -->

You are operating within a Universal AI Agent Army repository.
For all non-trivial tasks:
1. Always follow the guidelines in `AGENTS.md` and `canonical/agents/orchestrator.md`.
2. Inspect `PROJECT_STATE.md` to maintain situational awareness of the project roadmap.
3. Coordinate work using the standardized patterns in `canonical/workflows/`.
4. Delegate specialist tasks to personas defined in `canonical/agents/`.
"""
    orch_rule.write_text(content.strip() + "\n", encoding="utf-8")
    created.append(orch_rule)

    # 2. Skill stubs pointing back to canonical
    for skill_path in sorted(SKILLS_DIR.iterdir()):
        if skill_path.is_dir() and (skill_path / "SKILL.md").exists():
            target_skill_dir = skills_dir / skill_path.name
            target_skill_dir.mkdir(parents=True, exist_ok=True)
            stub_file = target_skill_dir / "SKILL.md"
            stub_content = f"""---
name: "{skill_path.name}"
description: "Canonical skill wrapper for {skill_path.name}. References canonical/skills/{skill_path.name}/SKILL.md."
---

<!-- Generated by adapters/compile.py. Single source of truth is canonical/skills/{skill_path.name}/SKILL.md -->
# Skill: {skill_path.name}

This skill references the canonical definition at:
`canonical/skills/{skill_path.name}/SKILL.md`

Refer directly to `canonical/skills/{skill_path.name}/SKILL.md` for full instructions and examples.
"""
            stub_file.write_text(stub_content.strip() + "\n", encoding="utf-8")
            created.append(stub_file)

    return created

